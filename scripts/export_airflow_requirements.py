"""Generate requirements.txt for the Airflow image from pyproject.toml.

Deliberately NOT `uv export`. A fully pinned export drags every transitive dependency to
the host lockfile's versions, and inside the Astro runtime image that means downgrading
packages Airflow itself depends on -- a dry-run resolve against runtime 3.3-12 wanted to
take cryptography 50.0.0 -> 49.0.0 and urllib3 2.8.0 -> 2.7.0. The image's constraints
file (/etc/pip-constraints.txt) is the authority on transitives there.

So the image gets only our *direct* dependencies. Those we call ourselves are pinned to the
exact version in uv.lock -- loose bounds let pip jump snowflake-connector-python from the
tested 4.7.1 to an untested 5.x major. Those the Airflow image already ships (IMAGE_OWNED)
keep only pyproject's lower bound, so the image stays the authority on them. Orchestration-only
packages (not needed on the host) are listed in AIRFLOW_ONLY below.
"""

import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Packages Airflow itself depends on. Pinning these to the host lockfile can downgrade the
# image's own copy (cryptography 50 -> 49 was observed), so they keep only a lower bound.
IMAGE_OWNED = {"cryptography", "requests", "python-dotenv"}

# Needed inside the image but pointless on the host, so kept out of pyproject.toml.
# Cosmos renders the dbt project as Airflow tasks (one per model/test).
AIRFLOW_ONLY = ["astronomer-cosmos>=1.16.0,<2"]

HEADER = """\
# GENERATED by scripts/export_airflow_requirements.py (`just export-reqs`) -- do not edit.
# Direct dependencies only; transitive pins come from Astro's constraints, not uv.lock.
# Packages the Astro runtime image already provides (apache-airflow, providers) are omitted.
"""


def _name(spec: str) -> str:
    """Bare package name from a requirement like 'boto3>=1.43.50'."""
    return re.split(r"[<>=!~\[; ]", spec, maxsplit=1)[0].lower()


def _locked_versions() -> dict[str, str]:
    lock = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
    return {pkg["name"].lower(): pkg["version"] for pkg in lock["package"]}


def main():
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    locked = _locked_versions()

    lines = []
    for spec in sorted(project["dependencies"], key=str.lower):
        name = _name(spec)
        if name in IMAGE_OWNED:
            lines.append(spec)
        else:
            lines.append(f"{name}=={locked[name]}")
    lines += AIRFLOW_ONLY
    (ROOT / "requirements.txt").write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote requirements.txt ({len(lines)} direct dependencies)")


if __name__ == "__main__":
    main()
